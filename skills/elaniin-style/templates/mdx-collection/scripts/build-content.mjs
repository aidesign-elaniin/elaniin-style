/*
  MDX collections -> metadata for site-map.ts. Runs before dev and build (predev / prebuild) and by hand: `npm run content`.
  For every src/content/<name>/ that holds .mdx files it writes src/content/<name>.generated.ts with `items`.
  The body stays in the .mdx file (rendered by the [slug] page); only the frontmatter is read here.
  Frontmatter (values with ":" go in "quotes"): title (required) · summary · date (YYYY-MM-DD, required) · author · image { src, alt } · placeholder (true while filler) · slug (default: file name)
*/
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const ROOT = "src/content";
const errors = [];
for (const dir of fs.readdirSync(ROOT, { withFileTypes: true }).filter((e) => e.isDirectory())) {
  const files = fs.readdirSync(path.join(ROOT, dir.name)).filter((f) => f.endsWith(".mdx"));
  if (!files.length) continue;
  const items = [];
  for (const f of files) {
    const at = `${ROOT}/${dir.name}/${f}`;
    let data;
    try {
      ({ data } = matter(fs.readFileSync(path.join(ROOT, dir.name, f), "utf8")));
    } catch (e) {
      errors.push(`${at}: invalid frontmatter (${e.reason ?? e.message}). Put values that contain ":" inside "quotes".`);
      continue;
    }
    const slug = data.slug ?? f.replace(/\.mdx$/, "");
    const date = data.date instanceof Date ? data.date.toISOString().slice(0, 10) : String(data.date ?? "");
    if (!data.title) errors.push(`${at}: title missing`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) errors.push(`${at}: date must be YYYY-MM-DD`);
    if (typeof data.placeholder !== "boolean") errors.push(`${at}: placeholder must be true or false`);
    if (data.image && !data.image.alt) errors.push(`${at}: image.alt missing`);
    if (items.some((i) => i.slug === slug)) errors.push(`${at}: duplicated slug ${slug}`);
    items.push({
      slug,
      title: data.title,
      ...(data.summary ? { summary: data.summary } : {}),
      body: [], // the body lives in the .mdx file
      image: { src: data.image?.src ?? "/images/placeholder-16x10.svg", alt: data.image?.alt ?? `Imagen de relleno de ${data.title}` },
      placeholder: data.placeholder,
      date,
      ...(data.author ? { author: data.author } : {}),
    });
  }
  items.sort((a, b) => b.date.localeCompare(a.date));
  fs.writeFileSync(
    path.join(ROOT, `${dir.name}.generated.ts`),
    `// GENERATED by scripts/build-content.mjs from src/content/${dir.name}/*.mdx. Do not edit.\nimport type { Item } from "./types";\n\nexport type Entry = Item & { date: string; author?: string };\nexport const items: Entry[] = ${JSON.stringify(items, null, 2)};\n`,
  );
  console.log(`content: ${dir.name} -> ${items.length} entries`);
}
if (errors.length) {
  console.error(errors.map((e) => `  - ${e}`).join("\n"));
  process.exit(1);
}
